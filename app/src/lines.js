  /** 秒 → 「3 小时 12 分」/「48 分钟」/「不到 1 分钟」 */
  function fmtDur(sec) {
    const total = Math.max(0, Math.floor(Number(sec) || 0));
    if (total < 60) return "不到 1 分钟";
    const h = Math.floor(total / 3600);
    const m = Math.floor((total % 3600) / 60);
    if (!h) return m + " 分钟";
    return m ? h + " 小时 " + m + " 分" : h + " 小时";
  }

  /** 里程碑台词（app.js 的 celebrateCompanion 用），{h} 是小时数 */
  const COMPANY_MARKS = [
    "陪你满 {h} 小时了，星星给你。",
    "{h} 小时了，老大。海里我一直在。",
    "已经陪你 {h} 小时啦，这点时间不算什么。",
    "第 {h} 个小时，我记着呢。",
  ];

  function companionLine(hours) {
    const h = String(Math.max(1, Math.round(Number(hours) || 1)));
    return COMPANY_MARKS[Math.floor(Math.random() * COMPANY_MARKS.length)].replace(/\{h\}/g, h);
  }

  function nudgeMoney(n) {
    if (!(n > 0)) return "";
    return n >= 1 ? "¥" + n.toFixed(2) : "¥" + n.toFixed(3);
  }

  /** 闲置搭话：返回 { text, ctx, at }，形状与 pick() 一致（view-bubble 直接吃这个） */
  function pickNudge(s) {
    s = s || XJ.state.store.state;
    const unread = (s.sessions || []).reduce((n, x) => n + (x.unread || 0), 0);
    const spent = s.usage ? Number(s.usage.today) || 0 : 0;
    const hour = new Date().getHours();
    const night = hour >= 0 && hour < 6;

    let key = Math.random() < 0.5 ? "soon" : "long";
    if (unread > 0) key = "unread";
    else if (spent > 0 && Math.random() < 0.4) key = "money";
    else if (night && Math.random() < 0.6) key = "night";
    // 陪伴类只在独立窗（有账本）时才参与，且排在后面，别盖过「有未读」这种真信息
    else if (s.companion && Math.random() < 0.35) key = "company";

    const comp = s.companion;
    const pool = NUDGES[key] || NUDGES.soon;
    const filled = pool
      .map((t) =>
        t
          .replace(/\{n\}/g, String(unread))
          .replace(/\{cost\}/g, nudgeMoney(spent))
          .replace(/\{dur\}/g, comp ? fmtDur(comp.today_sec) : "")
          .replace(/\{days\}/g, comp ? String(comp.days_known) : "")
          .replace(/\{streak\}/g, comp ? String(comp.streak_days) : "")
      )
      .filter(Boolean);
    const usable = filled.length > 1 ? filled.filter((t) => t !== LAST.text) : filled;
    const text = usable[Math.floor(Math.random() * usable.length)] || filled[0];
    LAST.text = text;
    return { text, ctx: "idle", at: Date.now(), nudge: key };
  }

  XJ.lines = { pick, pickNudge, contextOf, companionLine, fmtDur };
